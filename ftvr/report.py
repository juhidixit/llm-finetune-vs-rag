"""Build results/RESULTS.md from results/metrics/*.json and results/preds/*.jsonl."""

from __future__ import annotations

import json
from pathlib import Path

from . import metrics

# Assumption used only to turn measured CPU time into dollars. Change it to your own price.
PRICE_PER_HOUR = 0.18  # USD, one 4-vCPU on-demand cloud instance (about the list price of an AWS c7i.xlarge)


def _load(res: Path) -> dict[str, dict]:
    return {p.stem: json.loads(p.read_text()) for p in sorted((res / "metrics").glob("*.json"))}


def _preds(res: Path, name: str):
    p = res / "preds" / f"{name}.jsonl"
    if not p.exists():
        return None, None
    rows = [json.loads(line) for line in p.open()]
    return [r["gold"] for r in rows], [r["pred"] for r in rows]


def pct(x, d=1):
    return "–" if x is None else f"{100 * x:.{d}f}"


def ms(x):
    return "–" if x is None else (f"{x:.2f}" if x < 10 else f"{x:.0f}")


def mins(s):
    return "–" if s is None else (f"{s:.1f} s" if s < 120 else f"{s / 60:.0f} min")


MAIN = [
    ("tfidf-lr-test", "TF-IDF + logistic regression", "classic"),
    ("minilm-lr-test", "MiniLM embeddings + logistic regression", "classic"),
    ("minilm-knn10-test", "MiniLM kNN vote (k=10)", "retrieval only"),
    ("zeroshot-test", "Qwen2.5-0.5B zero-shot, 77 intents in prompt", "prompting"),
    ("rag-k10-all-test", "Qwen2.5-0.5B + 10 retrieved labelled examples", "RAG (retrieval-augmented ICL)"),
    ("lora-r16-test", "Qwen2.5-0.5B LoRA r=16, all linear layers", "fine-tuning"),
    ("qlora-r16-test", "Qwen2.5-0.5B QLoRA r=16 (NF4 4-bit base)", "fine-tuning"),
]


def best_k(M: dict) -> int:
    """k chosen on the validation split (the test run uses only this k)."""
    vals = {k: M[f"rag-k{k}-all-val"]["accuracy"] for k in (5, 10, 20) if f"rag-k{k}-all-val" in M}
    return max(vals, key=vals.get) if vals else 10


def build(res: Path) -> str:
    M = _load(res)
    K = best_k(M)
    main = [(key.replace("rag-k10", f"rag-k{K}"), lab.replace("10 retrieved", f"{K} retrieved"), fam) for key, lab, fam in MAIN]
    L = [
        "# Results",
        "",
        "All numbers below were produced by `scripts/run_all.sh` on the machine listed at the end of",
        "this file and are regenerated by `python -m ftvr.run report`. Test set: official Banking77 test split",
        "(3,080 messages, 40 per intent). Training/retrieval pool: Banking77 train minus a stratified 10%",
        "validation split (9,000 messages). Accuracy CIs are 95% bootstrap intervals over test messages.",
        "",
    ]

    L += [
        "## 1. Main comparison (test)",
        "",
        "| Method | Family | Accuracy | 95% CI | Macro-F1 | ECE | Acc. @80% coverage | Prompt tokens | Throughput (ms/msg, batch 16) | Online p50 / p95 (ms, batch 1) | Train time | Trainable params |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for key, label, fam in main:
        m = M.get(key)
        if not m:
            continue
        ci = m.get("accuracy_ci95", [None, None])
        ol = m.get("online_latency", {})
        tr = m.get("train", {})
        tsec = tr.get("train_seconds", m.get("train_seconds"))
        tp = tr.get("trainable_params")
        tp_s = "–" if tp is None else f"{tp / 1e6:.1f} M ({tr.get('trainable_pct', 0):.2f}%)"
        L.append(
            f"| {label} | {fam} | **{pct(m['accuracy'])}** | {pct(ci[0])}–{pct(ci[1])} | {pct(m['macro_f1'])} | "
            f"{pct(m.get('ece'))} | {pct(m.get('acc_at_80pct_coverage'))} | {m.get('prompt_tokens_mean', 0):.0f} | "
            f"{ms(m.get('throughput_ms_per_example'))} | {ms(ol.get('p50_ms'))} / {ms(ol.get('p95_ms'))} | {mins(tsec)} | "
            f"{tp_s} |"
        )
    L += [
        "",
        "ECE and coverage use the probability of the emitted label path under constrained decoding",
        '(classic baselines have no comparable score here, so those cells are blank). "Acc. @80% coverage" is',
        "accuracy on the 80% most confident messages, i.e. if the 20% least confident went to a human agent.",
        "",
    ]

    # significance
    pairs = [
        ("lora-r16-test", "minilm-lr-test"),
        ("lora-r16-test", f"rag-k{K}-all-test"),
        (f"rag-k{K}-all-test", "minilm-knn10-test"),
        ("qlora-r16-test", "lora-r16-test"),
    ]
    sig = []
    for a, b in pairs:
        ga, pa = _preds(res, a)
        gb, pb = _preds(res, b)
        if pa and pb:
            sig.append(
                f"| {a.removesuffix('-test')} vs {b.removesuffix('-test')} | {pct(metrics.accuracy(ga, pa) - metrics.accuracy(gb, pb), 2)} pp | {metrics.paired_bootstrap_p(ga, pa, pb):.3f} |"
            )
    if sig:
        L += [
            "Paired bootstrap (10,000 resamples of the same test messages); p = share of resamples where A is not better than B:",
            "",
            "| A vs B | Accuracy difference | p |",
            "|---|---|---|",
            *sig,
            "",
        ]

    # cost
    rows = []
    for key, label, _ in main:
        m = M.get(key)
        if not m or not m.get("throughput_ms_per_example"):
            continue
        cpu_h = m["throughput_ms_per_example"] / 1000 * 1e6 / 3600
        tr = m.get("train", {})
        tsec = tr.get("train_seconds", m.get("train_seconds", 0)) or 0
        rows.append(
            f"| {label} | {cpu_h:.2f} | ${cpu_h * PRICE_PER_HOUR:.2f} | {mins(tsec) if tsec else '–'} | ${tsec / 3600 * PRICE_PER_HOUR:.2f} |"
        )
    if rows:
        L += [
            "## 2. Cost per million messages",
            "",
            f"Measured batch-16 throughput on one 4-vCPU machine, converted at an **assumed** ${PRICE_PER_HOUR:.2f}/hour",
            "(roughly the on-demand list price of a 4-vCPU cloud instance; edit `PRICE_PER_HOUR` in `ftvr/report.py`).",
            "No GPU was used. Training cost is one run, not including the hyperparameter search we did not do.",
            "",
            "| Method | Instance-hours / 1M msgs | Serving $ / 1M msgs | Training time | Training $ |",
            "|---|---|---|---|---|",
            *rows,
            "",
        ]

    # RAG k
    ks = [(k, M.get(f"rag-k{k}-all-val")) for k in (5, 10, 20)]
    if any(m for _, m in ks):
        L += [
            "## 3. RAG ablation: number of retrieved examples (validation split, 1,003 messages; chosen k is used on test)",
            "",
            "| k | Accuracy | Label recall@k of retriever | Prompt tokens | ms/msg |",
            "|---|---|---|---|---|",
        ]
        for k, m in ks:
            if m:
                L.append(
                    f"| {k} | {pct(m['accuracy'])} | {pct(m.get('label_recall_at_k'))} | {m.get('prompt_tokens_mean', 0):.0f} | {ms(m.get('throughput_ms_per_example'))} |"
                )
        L.append("")

    # FT ablations
    abl = [
        ("lora-r4-test", "rank 4"),
        ("lora-r16-test", "rank 16 (default)"),
        ("lora-r64-test", "rank 64"),
        ("lora-r16-e2-test", "rank 16, 2 epochs"),
        ("lora-r16-attn-test", "rank 16, attention projections only"),
        ("qlora-r16-test", "rank 16, QLoRA NF4 base"),
        ("lora-r16-n10-test", "rank 16, 10 examples per intent (770), 3 epochs"),
        ("lora-r16-n30-test", "rank 16, 30 examples per intent (2,310), 3 epochs"),
    ]
    rows = []
    for key, lab in abl:
        m = M.get(key)
        if m:
            tr = m.get("train", {})
            rows.append(
                f"| {lab} | {pct(m['accuracy'])} | {pct(m['macro_f1'])} | {tr.get('n_train', '–')} | {tr.get('trainable_params', 0) / 1e6:.2f} M | {tr.get('adapter_bytes', 0) / 1e6:.1f} MB | {mins(tr.get('train_seconds'))} |"
            )
    if rows:
        L += [
            "## 4. Fine-tuning ablations (test)",
            "",
            "Defaults: lr 2e-4, cosine schedule, batch 16, 1 epoch, alpha = 2 x rank, dropout 0.05, loss on answer tokens only.",
            "",
            "| Variant | Accuracy | Macro-F1 | Train examples | Trainable params | Adapter size | Train time |",
            "|---|---|---|---|---|---|---|",
            *rows,
            "",
        ]

    # decoding
    rows = []
    for base, lab in [("zeroshot", "zero-shot"), (f"rag-k{K}-all", f"RAG k={K}"), ("lora-r16", "LoRA r=16")]:
        c, f = M.get(f"{base}-test"), M.get(f"{base}-free-test")
        if c and f:
            rows.append(f"| {lab} | {pct(c['accuracy'])} | {pct(f['accuracy'])} | {pct(f['invalid_rate'])} |")
    if rows:
        L += [
            "## 5. Constrained vs free decoding (test)",
            "",
            "Free decoding counts an output as correct only if it exactly matches an intent name after lower-casing.",
            "",
            "| Method | Constrained acc. | Free acc. | Free: invalid outputs |",
            "|---|---|---|---|",
            *rows,
            "",
        ]

    ni = M.get("newintent")
    if ni:
        L += [
            "## 6. New intents after deployment",
            "",
            f"Ten intents are treated as launched after training: {', '.join(ni['held_out_intents'])}.",
            'Rows marked "none" had their example index (or label list) updated with the new intents\' training examples but no',
            f"gradient update. Test: {ni['n_test_new']} messages from new intents, {ni['n_test_seen']} from the other 67.",
            "",
            "| Approach | Acc. new intents | Acc. seen intents | Acc. all | Retraining needed |",
            "|---|---|---|---|---|",
        ]
        for r in ni["rows"]:
            L.append(
                f"| {r['approach']} | {pct(r['acc_new_intents'])} | {pct(r['acc_seen_intents'])} | {pct(r['acc_all'])} | {r['retraining']} |"
            )
        L.append("")

    envs = {json.dumps(m.get("env"), sort_keys=True) for m in M.values() if m.get("env")}
    if envs:
        L += ["## Environment", "", *[f"- `{e}`" for e in sorted(envs)], ""]
    text = "\n".join(L)
    (res / "RESULTS.md").write_text(text)
    print(text)
    return text
